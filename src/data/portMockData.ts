const STORAGE_KEY = 'smartdock_state_v1';

export interface SmartDockStoredState {
  berths: PortBerth[];
  arrivals: ArrivalSchedule[];
  reservations: BerthReservation[];
  alerts: OperationalAlert[];
}

export function loadSmartDockState(): SmartDockStoredState {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (parsed.berths && parsed.arrivals && parsed.reservations) {
        return parsed;
      }
    }
  } catch (err) {
    console.warn('Failed to load smartdock state from localStorage:', err);
  }
  return {
    berths: INITIAL_BERTHS,
    arrivals: INITIAL_VESSEL_ARRIVALS,
    reservations: INITIAL_RESERVATIONS,
    alerts: INITIAL_OPERATIONAL_ALERTS,
  };
}

export function saveSmartDockState(state: SmartDockStoredState): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
  } catch (err) {
    console.warn('Failed to save smartdock state to localStorage:', err);
  }
}
