const STORAGE_KEY = 'fueltrust_records_v1';

export function loadStoredFuelRecords(): FuelRecord[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return INITIAL_FUEL_TRUST_RECORDS;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      // Re-run data checks in case format evolved
      return parsed.map((item: FuelRecord) => ({
        ...item,
        validationResult: runDataQualityChecks(item),
      }));
    }
  } catch (err) {
    console.warn('Failed to parse stored fuel records from localStorage, falling back to initial records.', err);
  }
  return INITIAL_FUEL_TRUST_RECORDS;
}

export function saveStoredFuelRecords(records: FuelRecord[]): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(records));
  } catch (err) {
    console.warn('Failed to persist fuel records to localStorage.', err);
  }
}
